'use strict';

/**
 * Database adapter router.
 *
 * Reads the DB_DRIVER environment variable and loads the matching adapter:
 *
 *   DB_DRIVER=mysql     → src/config/db.mysql.js   (default)
 *   DB_DRIVER=postgres  → src/config/db.postgres.js
 *
 * Every consumer in this codebase (controllers, setup scripts) imports THIS
 * file only — they never import a driver file directly. That single import
 * point is all you need to change when switching databases.
 *
 * ── Unified interface exported by both adapters ──────────────────────────
 *
 *   adapter.query(sql, params)
 *     Execute a query. Use ? for placeholders (auto-translated for postgres).
 *     Returns: { rows: object[], rowCount: number, insertId: number|null }
 *
 *   adapter.getClient()
 *     Acquire a dedicated connection / client from the pool.
 *     Returns: { query(sql, params), release() }
 *     Caller MUST call release() when done.
 *
 *   adapter.end()
 *     Drain the pool — call only in setup/teardown scripts, not in the server.
 *
 *   adapter.driver
 *     String identifier: 'mysql' | 'postgres'
 *
 * ── SQL dialect notes ────────────────────────────────────────────────────
 *
 *  The controller (enquiry.controller.js) builds SQL using the helpers below
 *  so that the same logical query works on both databases:
 *
 *   sql.INSERT_ENQUIRY   – INSERT with RETURNING id  (pg) or lastInsertId (mysql)
 *   sql.SELECT_BY_ID     – parameterised SELECT by primary key
 *   sql.SELECT_PAGE      – paginated list with optional WHERE status = ?
 *   sql.COUNT            – COUNT(*) with optional WHERE status = ?
 *   sql.UPDATE_STATUS    – UPDATE status WHERE id = ?
 *   sql.MARK_READ        – conditional status transition new→read
 *   sql.PREVIEW_FIELD    – how to truncate the message column for list view
 *
 *  These SQL fragments are generated by the getSql() helper exported below.
 */

const DRIVER = (process.env.DB_DRIVER || 'mysql').toLowerCase().trim();

const SUPPORTED = ['mysql', 'postgres'];
if (!SUPPORTED.includes(DRIVER)) {
  console.error(
    `[DB] Unknown DB_DRIVER="${DRIVER}". Must be one of: ${SUPPORTED.join(', ')}. Falling back to mysql.`
  );
}

// Load the correct adapter
const adapter =
  DRIVER === 'postgres'
    ? require('./db.postgres')
    : require('./db.mysql');

console.log(`[DB] Using driver: ${adapter.driver}`);

// ── Driver-aware SQL fragments ─────────────────────────────────────────────
/**
 * Returns SQL fragments tailored to the active driver.
 * The controller calls getSql() once and uses the returned object — it never
 * writes driver-specific SQL itself.
 */
function getSql() {
  if (adapter.driver === 'postgres') {
    return {
      // INSERT — RETURNING id gives us the new PK without a second query
      INSERT_ENQUIRY: `
        INSERT INTO enquiries (name, email, subject, message, ip_address, user_agent)
        VALUES (?, ?, ?, ?, ?, ?)
        RETURNING id`,

      // SELECT single row
      SELECT_BY_ID: `SELECT * FROM enquiries WHERE id = ?`,

      // Paginated list — SUBSTRING(message FROM 1 FOR 120) is ANSI SQL
      SELECT_PAGE: (hasStatus) => `
        SELECT id, name, email, subject,
               SUBSTRING(message FROM 1 FOR 120) AS message_preview,
               status, ip_address, created_at, updated_at
        FROM enquiries
        ${hasStatus ? 'WHERE status = ?' : ''}
        ORDER BY created_at DESC
        LIMIT ? OFFSET ?`,

      COUNT: (hasStatus) => `
        SELECT COUNT(*)::int AS total
        FROM enquiries
        ${hasStatus ? 'WHERE status = ?' : ''}`,

      UPDATE_STATUS: `UPDATE enquiries SET status = ? WHERE id = ?`,

      MARK_READ: `UPDATE enquiries SET status = 'read' WHERE id = ? AND status = 'new'`,

      // Normalise COUNT result — pg returns { total: <number> }
      getTotal: (row) => row.total,
    };
  }

  // ── MySQL fragments ──────────────────────────────────────────────────────
  return {
    INSERT_ENQUIRY: `
      INSERT INTO enquiries (name, email, subject, message, ip_address, user_agent)
      VALUES (?, ?, ?, ?, ?, ?)`,

    SELECT_BY_ID: `SELECT * FROM enquiries WHERE id = ?`,

    SELECT_PAGE: (hasStatus) => `
      SELECT id, name, email, subject,
             LEFT(message, 120) AS message_preview,
             status, ip_address, created_at, updated_at
      FROM enquiries
      ${hasStatus ? 'WHERE status = ?' : ''}
      ORDER BY created_at DESC
      LIMIT ? OFFSET ?`,

    COUNT: (hasStatus) => `
      SELECT COUNT(*) AS total
      FROM enquiries
      ${hasStatus ? 'WHERE status = ?' : ''}`,

    UPDATE_STATUS: `UPDATE enquiries SET status = ? WHERE id = ?`,

    MARK_READ: `UPDATE enquiries SET status = 'read' WHERE id = ? AND status = 'new'`,

    // MySQL COUNT returns { total: '5' } (string) — parse it
    getTotal: (row) => parseInt(row.total, 10),
  };
}

module.exports = { ...adapter, getSql };
